"""Настройки бота: «прайс-лист» мастера и всё, что зависит от места запуска.

Здесь почти нет логики — в основном данные. Если мастер поменяет цены,
правим этот файл и больше ничего не трогаем.

То, что у каждой установки своё — чей это бот, куда приходить клиенту, где
лежит ключ доступа, — вписано не сюда, а в соседний config.cfg; отсюда мы это
только читаем. Так код у всех одинаковый, а личное собрано в одном месте
и правится без Python: поставить бота другому мастеру — значит поправить
один текстовый файл.

Отдельно стоит путь к базе: его задаёт не человек, а площадка, на которой
бот запущен, поэтому он и приходит из переменной окружения. Ключ доступа
можно задать переменной по той же причине.
"""

import configparser
import os
from pathlib import Path

# Пути считаем от самого файла настроек, а не от рабочего каталога:
# так они находятся, откуда бы ни запускали main.py.
HERE = Path(__file__).parent

SETTINGS_FILE = HERE / "config.cfg"


# --- Файл настроек --------------------------------------------------------
# config.cfg читаем один раз при импорте: настройки не меняются на ходу,
# а лишние обращения к диску из фонового потока нам ни к чему.

def read_settings():
    """Разобрать config.cfg.

    interpolation=None выключает подстановку значений через знак процента.
    Файл заполняет человек, который про экранирование не знает, и «скидка 50%»
    в адресе не должна валить запуск.
    """
    parser = configparser.ConfigParser(interpolation=None)
    try:
        found = parser.read(SETTINGS_FILE, encoding="utf-8")
    except configparser.Error as error:
        # SystemExit, а не исключение: человеку нужен понятный текст, а не
        # трассировка стека. Дальше по файлу это правило работает везде.
        raise SystemExit(
            f"Не разобрала файл настроек {SETTINGS_FILE}:\n{error}"
        )

    if not found:
        raise SystemExit(
            f"Не нашла файл настроек {SETTINGS_FILE.name} рядом с кодом.\n"
            "В нём лежат адрес салона, телефон, VK ID мастера и имя файла\n"
            "с ключом доступа. Образец — в README, раздел «Настройки»."
        )
    return parser


SETTINGS = read_settings()


def raw_setting(section, key):
    """Значение из настроек как есть, без проверки на пустоту."""
    if not SETTINGS.has_option(section, key):
        raise SystemExit(
            f"В файле настроек {SETTINGS_FILE.name} нет строки «{key}» "
            f"в разделе [{section}].\n"
            "Добавьте её — образец с пояснениями есть в README."
        )
    return SETTINGS.get(section, key).strip()


def setting(section, key):
    """Непустая строка из настроек.

    Пустое значение — это почти всегда «собирался заполнить и забыл».
    Останавливаемся сразу: клиент не должен узнавать о забытом адресе
    из приветствия, в котором вместо адреса пусто.
    """
    value = raw_setting(section, key)
    if not value:
        raise SystemExit(
            f"В файле настроек {SETTINGS_FILE.name} пустая строка «{key}» "
            f"в разделе [{section}].\n"
            "Впишите значение после знака «=»."
        )
    return value


def number_setting(section, key):
    """Целое число из настроек. Пустая строка — ноль.

    Ноль для нас осмысленное значение («такого человека нет»), поэтому пустую
    строку можно к нему свести, а вот «двести три» — уже опечатка, и молчать
    о ней нельзя: бот бы просто не писал мастеру, и никто бы не понял почему.
    """
    value = raw_setting(section, key)
    if not value:
        return 0
    if not value.isdigit():
        raise SystemExit(
            f"В файле настроек {SETTINGS_FILE.name} строка «{key}» "
            f"в разделе [{section}] должна быть числом, а там «{value}»."
        )
    return int(value)


# --- Ключ доступа сообщества ----------------------------------------------
# Имя файла с ключом берём из настроек, а сам ключ там не держим: config.cfg
# едет в git, и ключ в нём рано или поздно оказался бы в репозитории.
TOKEN_FILE = HERE / setting("community", "token_file")


def read_token():
    """Ключ доступа сообщества: из переменной окружения или из файла.

    Переменная важнее файла: файл с ключом лежит в `.gitignore`, поэтому
    на хостинг, куда код приезжает через git, он не попадёт — там ключ
    задаётся только переменной VK_TOKEN. Файл остаётся для запуска
    на своём компьютере.
    """
    token = os.environ.get("VK_TOKEN", "").strip()
    if token:
        return token

    if TOKEN_FILE.exists():
        return TOKEN_FILE.read_text(encoding="utf-8").strip()

    raise SystemExit(
        "Не нашла ключ доступа сообщества.\n"
        f"На своём компьютере: положите его в {TOKEN_FILE.name} рядом с кодом "
        f"(имя файла задано в {SETTINGS_FILE.name}).\n"
        "На хостинге: задайте переменную окружения VK_TOKEN."
    )


VK_TOKEN = read_token()


