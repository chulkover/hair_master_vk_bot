# Пути считаем от самого файла настроек, а не от рабочего каталога:
# так они находятся, откуда бы ни запускали main.py.
HERE = Path(__file__).parent

TOKEN_FILE = HERE / "token.txt"


def read_token():
    """Ключ доступа сообщества: из переменной окружения или из token.txt.

    Переменная важнее файла: `token.txt` в `.gitignore`, поэтому на хостинг,
    куда код приезжает через git, он не попадёт — там ключ задаётся только
    переменной VK_TOKEN. Файл остаётся для запуска на своём компьютере.
    """
    token = os.environ.get("VK_TOKEN", "").strip()
    if token:
        return token

    if TOKEN_FILE.exists():
        return TOKEN_FILE.read_text(encoding="utf-8").strip()

    # SystemExit, а не исключение: человеку нужен понятный текст, а не
    # трассировка стека из-за отсутствующего файла.
    raise SystemExit(
        "Не нашла ключ доступа сообщества.\n"
        "На своём компьютере: положите его в token.txt рядом с кодом.\n"
        "На хостинге: задайте переменную окружения VK_TOKEN."
    )


